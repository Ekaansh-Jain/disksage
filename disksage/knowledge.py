"""The baked-in brain.

Every entry here is a piece of knowledge that used to require a smart model to
"just know". Encoding it once makes the tool fast, offline, free, and — most
importantly — *consistent*. The LLM is only consulted for things NOT covered
here (see classify.py).

Tiers:
    safe   -> regenerates on its own; deleting it costs nothing but time
    review -> reclaimable, but you choose (a reinstall/redownload is needed)
    keep   -> never suggest deleting; real data or sandbox state

Rules are matched most-specific-first. The first match wins.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from fnmatch import fnmatch

HOME = os.path.expanduser("~")


@dataclass(frozen=True)
class Hit:
    tier: str          # "safe" | "review" | "keep"
    label: str         # human name for the thing
    why: str           # one line: why it's safe / why to keep
    source: str = "knowledge"


@dataclass(frozen=True)
class Rule:
    # match if fnmatch(full_path, path_glob) OR basename matches name_glob
    tier: str
    label: str
    why: str
    path_glob: str | None = None
    name_glob: str | None = None


def _h(p: str) -> str:
    return os.path.join(HOME, p)


