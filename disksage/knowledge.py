def look_up(path: str) -> Hit | None:
    """Return knowledge about a path, or None if we don't recognise it."""
    base = os.path.basename(path.rstrip("/"))
    for r in RULES:
        if r.path_glob and fnmatch(path, r.path_glob):
            return Hit(r.tier, r.label, r.why)
        if r.name_glob and fnmatch(base, r.name_glob):
            return Hit(r.tier, r.label, r.why)
    return None


# Large loose files aren't caches — they're YOUR data. We classify them by
# extension only to give a helpful label; the tier is always "review" and the
# reason makes clear the tool can't know if you still need it.
_EXT_KINDS = {
    "ML model": {".h5", ".hdf5", ".pt", ".pth", ".ckpt", ".safetensors",
                 ".pb", ".onnx", ".tflite", ".pkl", ".joblib", ".gguf", ".ggml"},
    "dataset": {".csv", ".tsv", ".parquet", ".jsonl", ".arrow",
                ".npy", ".npz", ".mat", ".feather"},
    "media file": {".mp4", ".mov", ".avi", ".mkv", ".wav", ".flac", ".psd"},
    "archive": {".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".rar",
                ".7z", ".dmg", ".iso", ".pkg"},
}


def file_kind(path: str) -> Hit:
    """Label a large loose file by extension. Always 'review' — it's user data."""
    ext = os.path.splitext(path)[1].lower()
    for label, exts in _EXT_KINDS.items():
        if ext in exts:
            return Hit("review", f"Large {label}",
                       "your file — delete only if you can recreate it", "extension")
    return Hit("review", "Large file",
               "your file — delete only if you can recreate it", "extension")

